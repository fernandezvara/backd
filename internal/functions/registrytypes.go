package functions

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"slices"

	"github.com/fernandezvara/backd/internal/registry"
	"github.com/fernandezvara/backd/internal/typegen"
)

// ModuleName is what functions import defineFunction from.
const ModuleName = "@backd/functions"

// runtimeFile is the module ModuleName maps to, inside the project's hidden RuntimeDir:
// defineFunction returns its handler unchanged, so it costs nothing at run time.
const runtimeFile = "functions.js"

const runtimeSource = `// Generated by backd. defineFunction names a function for its types and returns its handler.
// @ts-self-types="../backd.d.ts"
export const defineFunction = (_name, handler) => handler;
`

// importMapFile is the hidden import map a build passes to Deno when the project's own
// deno.json doesn't map ModuleName.
const importMapFile = ".backd-importmap.json"

// writeIfChanged writes the file unless it already holds data. It reports whether it wrote.
func writeIfChanged(path string, data []byte) (bool, error) {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, err
	}
	return true, os.WriteFile(path, data, 0o644)
}

// writeRuntime writes the module defineFunction runs on.
func writeRuntime(dir string) error {
	_, err := writeIfChanged(filepath.Join(dir, registry.RuntimeDir, runtimeFile), []byte(runtimeSource))
	return err
}

// WriteTypes writes backd.d.ts (and the runtime module it goes with) into the functions
// project of every database of the realm that has functions; realm "" means every realm. It
// returns the files it changed, and what the generator couldn't express. With dryRun it
// writes nothing and returns the files that would change.
func WriteTypes(reg *registry.Registry, realm, config string, dryRun bool) (changed, warnings []string, err error) {
	for _, db := range reg.Databases() {
		if db.Functions == nil || (realm != "" && db.Realm != realm) {
			continue
		}
		out, err := typegen.GenerateFunctions(reg, db.Realm, db.Name, config)
		if err != nil {
			return changed, warnings, err
		}
		warnings = append(warnings, out.Warnings...)
		path := filepath.Join(db.Functions.Dir, registry.TypesFile)
		if dryRun {
			if old, err := os.ReadFile(path); err != nil || string(old) != out.Types {
				changed = append(changed, path)
			}
			continue
		}
		wrote, err := writeIfChanged(path, []byte(out.Types))
		if err != nil {
			return changed, warnings, err
		}
		if wrote {
			changed = append(changed, path)
		}
		if err := writeRuntime(db.Functions.Dir); err != nil {
			return changed, warnings, err
		}
	}
	slices.Sort(warnings)
	return changed, slices.Compact(warnings), nil
}

// importMapArgs returns the arguments mapping ModuleName for a build, or none when the
// project maps it itself or uses a configuration backd doesn't read.
func importMapArgs(dir string) ([]string, error) {
	if err := writeRuntime(dir); err != nil {
		return nil, err
	}
	var imports map[string]any
	var rest map[string]any
	data, err := os.ReadFile(filepath.Join(dir, "deno.json"))
	switch {
	case errors.Is(err, os.ErrNotExist):
		if _, err := os.Stat(filepath.Join(dir, "deno.jsonc")); err == nil {
			return nil, nil // comments: not read here, so the project maps the module itself
		}
	case err != nil:
		return nil, err
	default:
		if err := json.Unmarshal(data, &rest); err != nil {
			return nil, nil // Deno reports an invalid deno.json
		}
		if _, ok := rest["importMap"]; ok {
			return nil, nil
		}
		imports, _ = rest["imports"].(map[string]any)
	}
	if _, ok := imports[ModuleName]; ok {
		return nil, nil
	}
	merged := map[string]any{}
	for k, v := range imports {
		merged[k] = v
	}
	merged[ModuleName] = "./" + registry.RuntimeDir + "/" + runtimeFile
	doc := map[string]any{"imports": merged}
	if scopes, ok := rest["scopes"]; ok {
		doc["scopes"] = scopes
	}
	b, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, err
	}
	if _, err := writeIfChanged(filepath.Join(dir, importMapFile), b); err != nil {
		return nil, fmt.Errorf("import map: %w", err)
	}
	return []string{"--import-map", importMapFile}, nil
}
