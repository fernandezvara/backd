// migrationDatabases lists the databases of reg with at least one migration step.
func migrationDatabases(reg *registry.Registry) []*registry.Database {
	var out []*registry.Database
	for _, db := range reg.Databases() {
		if len(db.MigratingCollections()) > 0 {
			out = append(out, db)
		}
	}
	return out
}

// buildMigrations bundles the migrations of one database into _migrations/.build: one bundle per
// collection holding all its steps, type-checked always (design/schema-versioning.md §6.1).
// The previous build is replaced only when every collection bundled.
func buildMigrations(ctx context.Context, db *registry.Database, opts Options) error {
	colls := db.MigratingCollections()
	// The imports are checked first: the file and line are a better message than a bundler's.
	var errs []error
	for _, c := range colls {
		for _, n := range c.Migrations {
			if err := registry.CheckMigrationImports(filepath.Join(c.Dir, registry.SchemaMigrationFile(n))); err != nil {
				errs = append(errs, err)
			}
		}
	}
	if err := errors.Join(errs...); err != nil {
		return err
	}
	source, err := registry.MigrationSourceHash(db)
	if err != nil {
		return err
	}
	buildDir := db.MigrationsBuildDir()
	if err := os.MkdirAll(buildDir, 0o755); err != nil {
		return err
	}
	m := registry.MigrationManifest{Deno: registry.DenoVersion, Source: source, Collections: map[string]registry.ManifestBundle{}}
	for _, c := range colls {
		b, err := bundleMigrations(ctx, db, c, opts)
		if err != nil {
			return fmt.Errorf("collection %s: %w", c.Name, err)
		}
		sum := sha256.Sum256(b)
		hash := hex.EncodeToString(sum[:])
		file := c.Name + "-" + hash[:16] + ".js"
		if err := os.WriteFile(filepath.Join(buildDir, file), b, 0o644); err != nil {
			return err
		}
		m.Collections[c.Name] = registry.ManifestBundle{Bundle: file, SHA256: hash}
		opts.Log("bundled migrations of %s/%s/%s → %s (%d bytes)", db.Realm, db.Name, c.Name, file, len(b))
	}
	data, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	tmp := filepath.Join(buildDir, registry.ManifestFile+".tmp")
	if err := os.WriteFile(tmp, append(data, '\n'), 0o644); err != nil {
		return err
	}
	if err := os.Rename(tmp, filepath.Join(buildDir, registry.ManifestFile)); err != nil {
		return err
	}
	keep := map[string]bool{registry.ManifestFile: true}
	for _, b := range m.Collections {
		keep[b.Bundle] = true
	}
	return pruneExcept(buildDir, keep)
}

// bundleMigrations bundles one collection's steps with `deno bundle --check`. The entry is a
// generated module in the build folder that imports each step and lists them in order:
//
//	export const steps = [{ to: 2, run: step2 }, { to: 3, run: step3 }];
func bundleMigrations(ctx context.Context, db *registry.Database, c *registry.Collection, opts Options) ([]byte, error) {
	buildDir := db.MigrationsBuildDir()
	rel, err := filepath.Rel(buildDir, c.Dir)
	if err != nil {
		return nil, err
	}
	rel = filepath.ToSlash(rel)
	var src strings.Builder
	src.WriteString("// Generated by backd-server functions build: do not edit.\n")
	for _, n := range c.Migrations {
		fmt.Fprintf(&src, "import step%d from %q;\n", n, rel+"/"+registry.SchemaMigrationFile(n))
	}
	src.WriteString("export const steps = [\n")
	for _, n := range c.Migrations {
		fmt.Fprintf(&src, "  { to: %s, run: step%d },\n", strconv.Itoa(n), n)
	}
	src.WriteString("];\n")
	entry := filepath.Join(buildDir, "entry-"+c.Name+".ts")
	if err := os.WriteFile(entry, []byte(src.String()), 0o644); err != nil {
		return nil, err
	}
	defer func() { _ = os.Remove(entry) }()

	out, err := os.CreateTemp("", "backd-migration-*.js")
	if err != nil {
		return nil, err
	}
	out.Close()
	defer func() { _ = os.Remove(out.Name()) }()
	// Always --check: a type error in a migration corrupts data instead of failing a call.
	cmd := exec.CommandContext(ctx, opts.Deno, "bundle", "--platform=deno", "--quiet", "--check", "--output", out.Name(), entry)
	cmd.Dir = buildDir
	cmd.Env = append(os.Environ(), "NO_COLOR=1", "DENO_NO_UPDATE_CHECK=1")
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		msg := strings.TrimSpace(stderr.String())
		if msg == "" {
			msg = err.Error()
		}
		if strings.Contains(msg, "schema.d.ts") {
			msg += "\n(schema.d.ts is generated by `backd types`)"
		}
		return nil, errors.New("deno bundle failed:\n" + msg)
	}
	return os.ReadFile(out.Name())
}
