package admin

import (
	"errors"
	"fmt"

	"github.com/fernandezvara/backd/internal/cli/clicore"

	"github.com/fernandezvara/kli"

	"github.com/fernandezvara/backd/internal/cmdutil"
)

// secretCreate creates a field key: generated here by the server and printed once, or imported
// from --value. The key goes to standard output alone, so it can be redirected to a file.
func secretCreate(c *kli.CommandContext, o Opener) error {
	s, err := o.Open(c)
	if err != nil {
		return err
	}
	defer s.Close()
	t := s.t
	if typ := cmdutil.Str(c, "type"); typ != "key" {
		return cmdutil.UsageErr(fmt.Errorf("--type must be key (plain secrets are set with `backd secret set`), got %q", typ))
	}
	generate, src := cmdutil.Flag(c, "generate"), cmdutil.Str(c, "value")
	if generate == (src != "") {
		return cmdutil.UsageErr(errors.New("give exactly one of --generate and --value"))
	}
	name := cmdutil.Str(c, "name")
	body := map[string]any{"name": name, "type": "key"}
	if err := keyValue(c, body); err != nil {
		return err
	}
	uio := cmdutil.IOOf(c)
	proof, err := t.Proof(uio)
	if err != nil {
		return err
	}
	var out struct {
		Name        string `json:"name"`
		Fingerprint string `json:"fingerprint"`
		Key         string `json:"key"`
	}
	if err := t.Adm.Secrets.Create(t.Ctx, body, &out, clicore.WithProof(proof)...); err != nil {
		var ae *clicore.APIError
		if cmdutil.Flag(c, "skip-existing") && errors.As(err, &ae) && ae.Status == 409 {
			fmt.Fprintf(uio.Stderr, "Key %s exists already: left as it is.\n", name)
			return nil
		}
		return err
	}
	if out.Key != "" {
		return showKey(c, uio, out, out.Key, fmt.Sprintf("Key %s created, fingerprint %s:%s.\nThis is the only time the key is shown. Store it somewhere safe outside backd: if it is lost, every value encrypted with it is lost.", out.Name, out.Name, out.Fingerprint))
	}
	return showKey(c, uio, out, "", fmt.Sprintf("Key %s imported, fingerprint %s:%s. Check it matches your copy.", out.Name, out.Name, out.Fingerprint))
}

// keyValue puts the key a command creates or rotates to into its body: generated by the
// server (--generate) or read from --value (key:, env: or file:).
func keyValue(c *kli.CommandContext, body map[string]any) error {
	if cmdutil.Flag(c, "generate") {
		body["generate"] = true
		return nil
	}
	v, err := cmdutil.ReadKeySource(cmdutil.Str(c, "value"), c.Getenv, c.Stderr())
	if err != nil {
		return err
	}
	body["value"] = v
	return nil
}

// showKey prints the answer of a key command: all of it as JSON with --json; else a generated
// key alone on standard output (so it can be redirected), and the message on standard error.
func showKey(c *kli.CommandContext, uio cmdutil.IO, answer any, key, message string) error {
	if cmdutil.Flag(c, "json") {
		return cmdutil.PrintJSON(uio.Stdout, answer)
	}
	if key != "" {
		fmt.Fprintln(uio.Stdout, key)
	}
	fmt.Fprintln(uio.Stderr, message)
	return nil
}

// keyIsHeld tells whether the realm has a key with that name, for a delete that needs a proof.
func keyIsHeld(t *clicore.Target, name string) (bool, error) {
	var page struct{ Items []secret }
	if err := t.Adm.Secrets.List(t.Ctx, &page); err != nil {
		return false, err
	}
	for _, s := range page.Items {
		if s.Database == "" && s.Org == "" && s.Name == name && s.Type == "key" {
			return true, nil
		}
	}
	return false, nil
}

// secretRotate gives a key a new value and re-wraps what it protects. A generated key goes to
// standard output once, like a created one.
func secretRotate(c *kli.CommandContext, o Opener) error {
	s, err := o.Open(c)
	if err != nil {
		return err
	}
	defer s.Close()
	t := s.t
	generate, resume, src := cmdutil.Flag(c, "generate"), cmdutil.Flag(c, "resume"), cmdutil.Str(c, "value")
	n := 0
	for _, set := range []bool{generate, resume, src != ""} {
		if set {
			n++
		}
	}
	if n != 1 {
		return cmdutil.UsageErr(errors.New("give exactly one of --generate, --value and --resume"))
	}
	body := map[string]any{}
	if resume {
		body["resume"] = true
	} else if err := keyValue(c, body); err != nil {
		return err
	}
	uio := cmdutil.IOOf(c)
	proof, err := t.Proof(uio)
	if err != nil {
		return err
	}
	name := cmdutil.Str(c, "name")
	var out struct {
		Fingerprint string `json:"fingerprint"`
		Previous    string `json:"previous_fingerprint"`
		Rewrapped   int    `json:"rewrapped"`
		Key         string `json:"key"`
	}
	if err := t.Adm.Secrets.Rotate(t.Ctx, name, body, &out, clicore.WithProof(proof)...); err != nil {
		return err
	}
	done := fmt.Sprintf("Key %s rotated: %s:%s replaces %s:%s, %d data key(s) wrapped again, no document rewritten.", name, name, out.Fingerprint, name, out.Previous, out.Rewrapped)
	if out.Key != "" {
		done += "\nThis is the only time the new key is shown. Store it somewhere safe outside backd, and keep the old one for backups made before today."
	}
	return showKey(c, uio, out, out.Key, done)
}
