func pythonOutput(t *testing.T) *Output {
	t.Helper()
	out, err := Generate(mustLoad(t), Options{Realm: "shop", Lang: "python"})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func TestGoldenShopPython(t *testing.T) {
	out := pythonOutput(t)
	golden := filepath.Join("testdata", "shop.types.py.txt")
	if *update {
		if err := os.WriteFile(golden, []byte(out.Types), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatal(err)
	}
	if string(want) != out.Types {
		t.Errorf("generated types differ from %s (run go test -update):\n%s", golden, out.Types)
	}
	// The fingerprint is shared with the other languages: it is what the clients send in X-Backd-Types for the
	// stale check.
	ts, err := Generate(mustLoad(t), Options{Realm: "shop"})
	if err != nil {
		t.Fatal(err)
	}
	if out.Info.Fingerprint != ts.Info.Fingerprint {
		t.Error("python and ts fingerprints differ: realm.json isn't shared")
	}
	for _, want := range []string{
		"class MainOrders(backd.Doc, _MainOrdersRequired, _MainOrdersOptional):",
		"status: Literal[\"new\", \"paid\", \"shipped\"]",
		"class MainInvoicesCreate(MainInvoicesInput):",
		"class ShopRealm:",
		"class AsyncShopRealm:",
		"def orders(self) -> backd.Collection[MainOrders]:",
		"def orders(self) -> backd.AsyncCollection[MainOrders]:",
		"class MainOrdersFields:",
		"STATUS = \"status\"",
	} {
		if !strings.Contains(out.Types, want) {
			t.Errorf("types.py is missing %q", want)
		}
	}
	if !strings.HasPrefix(out.Types, "# Generated by `backd types --lang python`") {
		t.Errorf("the header must mark the file as generated: %q", strings.SplitN(out.Types, "\n", 2)[0])
	}
}

func TestPythonGenerationIsDeterministic(t *testing.T) {
	if a, b := pythonOutput(t), pythonOutput(t); a.Types != b.Types {
		t.Error("two runs differ")
	}
}

// python runs a Python 3 interpreter on a script; the tests that need one skip without it.
func python(t *testing.T) string {
	t.Helper()
	for _, name := range []string{"python3", "python"} {
		if path, err := exec.LookPath(name); err == nil {
			return path
		}
	}
	t.Skip("python not installed")
	return ""
}

// pythonRealm loads a realm made of one collection with the given schema.
func pythonRealm(t *testing.T, schema string) *Output {
	t.Helper()
	dir := t.TempDir()
	for name, body := range map[string]string{
		"app/realm.yaml":                  "auth: disabled\n",
		"app/main/things/collection.yaml": "{}\n",
		"app/main/things/schema.json":     schema,
	} {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	reg, err := registry.Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	out, err := Generate(reg, Options{Realm: "app", Lang: "python"})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

// compilesPython checks that the file is valid Python (the interpreter's own parser).
func compilesPython(t *testing.T, src string) {
	t.Helper()
	cmd := exec.Command(python(t), "-c", "import sys; compile(sys.stdin.read(), 'types.py', 'exec')")
	cmd.Stdin = strings.NewReader(src)
	if res, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("python: %v\n%s\n%s", err, res, src)
	}
}

func TestPythonSchemaShapes(t *testing.T) {
	out := pythonRealm(t, `{
	  "type": "object",
	  "required": ["kind", "tree"],
	  "properties": {
	    "kind": {"enum": ["a-b", "c d", 2, true, null]},
	    "maybe": {"type": ["string", "null"]},
	    "maybe_kind": {"enum": ["x", "y"], "type": ["string", "null"]},
	    "grid": {"type": "array", "items": {"type": "array", "items": {"type": "integer"}}},
	    "by_name": {"type": "object", "additionalProperties": {"type": "object", "properties": {"n": {"type": "number"}}}},
	    "pair": {"type": "array", "prefixItems": [{"type": "string"}, {"type": "integer"}]},
	    "choice": {"oneOf": [{"type": "string"}, {"type": "integer"}]},
	    "mixed": {"type": ["string", "integer"]},
	    "tree": {"$ref": "#/$defs/node"},
	    "when": {"type": "string", "format": "date-time"},
	    "deep": {"type": "object", "required": ["a"], "properties": {"a": {"type": "object", "properties": {"b": {"type": "boolean"}}}}},
	    "no": {"not": {"type": "string"}}
	  },
	  "$defs": {"node": {"type": "object", "required": ["name"], "properties": {"name": {"type": "string"}, "children": {"type": "array", "items": {"$ref": "#/$defs/node"}}}}}
	}`)
	for _, want := range []string{
		`kind: Literal["a-b", "c d", 2, True]`,
		"maybe: str | None",
		`maybe_kind: Literal["x", "y"] | None`,
		"grid: list[list[int]]",
		"by_name: dict[str, MainThingsByNameValue]",
		"pair: tuple[str, int]",
		"choice: str | int",
		"mixed: str | int",
		"tree: MainThingsNode",
		"children: list[MainThingsNode]",
		"deep: MainThingsDeep",
		"a: MainThingsDeepA",
	} {
		if !strings.Contains(out.Types, want) {
			t.Errorf("types.py lacks %q:\n%s", want, out.Types)
		}
	}
	compilesPython(t, out.Types)
	mypyChecks(t, out.Types)
	if !strings.Contains(strings.Join(out.Warnings, "\n"), `keyword "not"`) {
		t.Errorf("no warning about the unsupported keyword in:\n%s", strings.Join(out.Warnings, "\n"))
	}
	if strings.Count(out.Types, "class MainThingsNode(") != 1 {
		t.Errorf("the recursive $ref must be emitted once:\n%s", out.Types)
	}
}

// A property name Python can't write (a keyword, a dash) goes in a TypedDict made the functional way, which the
// class that extends it joins.
func TestPythonUnwritableNames(t *testing.T) {
	out := pythonRealm(t, `{
	  "type": "object",
	  "required": ["from", "ok"],
	  "properties": {"from": {"type": "string"}, "my-field": {"type": ["boolean", "null"]}, "ok": {"type": "integer"}}
	}`)
	for _, want := range []string{
		`_MainThingsRequiredFields = TypedDict("_MainThingsRequiredFields", {"from": "str", "ok": "int"})`,
		`_MainThingsOptionalFields = TypedDict("_MainThingsOptionalFields", {"my-field": "bool | None"}, total=False)`,
		"class MainThings(backd.Doc, _MainThingsRequired, _MainThingsOptional):",
	} {
		if !strings.Contains(out.Types, want) {
			t.Errorf("types.py lacks %q:\n%s", want, out.Types)
		}
	}
	compilesPython(t, out.Types)
	mypyChecks(t, out.Types)
}

// mypyChecks type-checks generated code against the client in clients/python when mypy is there (the Python
// workflow always does).
func mypyChecks(t *testing.T, src string) {
	t.Helper()
	py := python(t)
	if res, err := exec.Command(py, "-m", "mypy", "--version").CombinedOutput(); err != nil {
		t.Skipf("mypy not installed: %s", res)
	}
	clientSrc, err := filepath.Abs(filepath.Join("..", "..", "clients", "python", "src"))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	file := filepath.Join(dir, "generated_types.py")
	if err := os.WriteFile(file, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(py, "-m", "mypy", "--strict", "--python-version", "3.10", "--cache-dir", filepath.Join(dir, ".mypy"), file)
	cmd.Env = append(os.Environ(), "MYPYPATH="+clientSrc)
	if res, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("mypy: %v\n%s\n%s", err, res, src)
	}
}

func TestPythonOutputPassesMypy(t *testing.T) {
	mypyChecks(t, pythonOutput(t).Types)
}
