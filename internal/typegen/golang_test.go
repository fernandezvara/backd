func goOutput(t *testing.T) *Output {
	t.Helper()
	reg, err := registry.Load("testdata")
	if err != nil {
		t.Fatal(err)
	}
	out, err := Generate(reg, Options{Realm: "shop", Lang: "go"})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func TestGoldenShopGo(t *testing.T) {
	out := goOutput(t)
	golden := filepath.Join("testdata", "shop.types.go.txt")
	if *update {
		if err := os.WriteFile(golden, []byte(out.Types), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatal(err)
	}
	if string(want) != out.Types {
		t.Errorf("generated types differ from %s (run go test -update):\n%s", golden, out.Types)
	}
	// The fingerprint is shared with the other languages: it is what the clients send in
	// X-Backd-Types for the stale check.
	ts, err := Generate(mustLoad(t), Options{Realm: "shop"})
	if err != nil {
		t.Fatal(err)
	}
	if out.Info.Fingerprint != ts.Info.Fingerprint {
		t.Error("go and ts fingerprints differ: realm.json isn't shared")
	}
	for _, want := range []string{"package backdtypes", "type MainOrders struct {\n\tclient.Base", "type ShopRealm struct{ Client *client.Client }", "func (d *ShopMain) Orders() *client.Typed[MainOrders]"} {
		if !strings.Contains(out.Types, want) {
			t.Errorf("types.go is missing %q", want)
		}
	}
	if !strings.HasPrefix(out.Types, "// Code generated by `backd types --lang go`") || !strings.Contains(strings.SplitN(out.Types, "\n", 2)[0], "DO NOT EDIT.") {
		t.Errorf("the header must mark the file as generated: %q", strings.SplitN(out.Types, "\n", 2)[0])
	}
}

func mustLoad(t *testing.T) *registry.Registry {
	t.Helper()
	reg, err := registry.Load("testdata")
	if err != nil {
		t.Fatal(err)
	}
	return reg
}

func TestGoPackageName(t *testing.T) {
	reg := mustLoad(t)
	out, err := Generate(reg, Options{Realm: "shop", Lang: "go", Package: "shopapi"})
	if err != nil || !strings.Contains(out.Types, "\npackage shopapi\n") {
		t.Errorf("%v\n%s", err, out.Types[:300])
	}
}

// TestGoOutputCompilesAndWorks writes the generated file into a package of this module (it imports
// pkg/client), builds it with a program that uses the typed accessors, and vets it.
func TestGoOutputCompilesAndWorks(t *testing.T) {
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("go not installed")
	}
	out := goOutput(t)
	dir, err := os.MkdirTemp(".", "gocheck")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(dir)
	if err := os.WriteFile(filepath.Join(dir, "types.go"), []byte(out.Types), 0o644); err != nil {
		t.Fatal(err)
	}
	use := `package backdtypes

import (
	"context"
	"testing"

	"github.com/fernandezvara/backd/pkg/client"
)

func TestUse(t *testing.T) {
	c, err := client.New(client.Options{URL: "http://localhost:1", Realm: "shop"})
	if err != nil {
		t.Fatal(err)
	}
	r := NewShopRealm(c)
	_ = r.Main().Orders()
	_ = MainOrdersFieldID
	_ = context.Background()
	var _ MainOrders
}
`
	if err := os.WriteFile(filepath.Join(dir, "use_test.go"), []byte(use), 0o644); err != nil {
		t.Fatal(err)
	}
	for _, args := range [][]string{{"vet", "./" + dir}, {"test", "-count=1", "./" + dir}} {
		cmd := exec.Command("go", args...)
		if res, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("go %s: %v\n%s", strings.Join(args, " "), err, res)
		}
	}
}

// goRealm loads a realm made of one collection with the given schema.
func goRealm(t *testing.T, schema string) *Output {
	t.Helper()
	dir := t.TempDir()
	for name, body := range map[string]string{
		"app/realm.yaml":                  "auth: disabled\n",
		"app/main/things/collection.yaml": "{}\n",
		"app/main/things/schema.json":     schema,
	} {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	reg, err := registry.Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	out, err := Generate(reg, Options{Realm: "app", Lang: "go"})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func compiles(t *testing.T, src string) {
	t.Helper()
	dir, err := os.MkdirTemp(".", "gocheck")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(dir)
	if err := os.WriteFile(filepath.Join(dir, "types.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	if res, err := exec.Command("go", "vet", "./"+dir).CombinedOutput(); err != nil {
		t.Fatalf("go vet: %v\n%s\n%s", err, res, src)
	}
}

func TestGoSchemaShapes(t *testing.T) {
	out := goRealm(t, `{
	  "type": "object",
	  "required": ["kind", "tree"],
	  "properties": {
	    "kind": {"enum": ["a-b", "c d", "2fa", "a-b"]},
	    "maybe": {"type": ["string", "null"]},
	    "maybe_kind": {"enum": ["x", "y"], "type": ["string", "null"]},
	    "grid": {"type": "array", "items": {"type": "array", "items": {"type": "integer"}}},
	    "by_name": {"type": "object", "additionalProperties": {"type": "object", "properties": {"n": {"type": "number"}}}},
	    "pair": {"type": "array", "prefixItems": [{"type": "string"}, {"type": "integer"}]},
	    "choice": {"oneOf": [{"type": "string"}, {"type": "integer"}]},
	    "mixed": {"type": ["string", "integer"]},
	    "tree": {"$ref": "#/$defs/node"},
	    "user_id": {"type": "string"},
	    "userId": {"type": "string"},
	    "a_b": {"type": "string"},
	    "aB": {"type": "string"},
	    "when": {"type": "string", "format": "date-time"},
	    "deep": {"type": "object", "required": ["a"], "properties": {"a": {"type": "object", "properties": {"b": {"type": "boolean"}}}}},
	    "no": {"not": {"type": "string"}}
	  },
	  "$defs": {"node": {"type": "object", "required": ["name"], "properties": {"name": {"type": "string"}, "children": {"type": "array", "items": {"$ref": "#/$defs/node"}}}}}
	}`)
	for _, want := range []string{
		"MainThingsKindAB MainThingsKind = \"a-b\"",
		"MainThingsKindCD MainThingsKind = \"c d\"",
		"MainThingsKind2fa MainThingsKind = \"2fa\"",
		"Maybe     *string",
		"MaybeKind *MainThingsMaybeKind",
		"Grid      [][]int64",
		"ByName    map[string]MainThingsByNameValue",
		"Pair      []any",
		"Choice    json.RawMessage",
		"Mixed     any",
		"Tree      MainThingsNode",
		"Children []MainThingsNode",
		"UserID *string `json:\"user_id,omitempty\"`",
		"UserId *string `json:\"userId,omitempty\"`",
		"AB *string `json:\"aB,omitempty\"`",
		"AB_ *string `json:\"a_b,omitempty\"`",
		"When      *time.Time",
		"Deep      *MainThingsDeep",
		"A MainThingsDeepA",
	} {
		if !strings.Contains(squash(out.Types), squash(want)) {
			t.Errorf("types.go lacks %q:\n%s", want, out.Types)
		}
	}
	compiles(t, out.Types)
	joined := strings.Join(out.Warnings, "\n")
	for _, want := range []string{`keyword "not"`, "tuple", "oneOf", "union of JSON types"} {
		if !strings.Contains(joined, want) {
			t.Errorf("no warning about %q in:\n%s", want, joined)
		}
	}
	// the enum constants don't repeat, and every name that two different things want gets a suffix
	if strings.Count(out.Types, "= \"a-b\"") != 1 {
		t.Errorf("a repeated enum value was emitted twice:\n%s", out.Types)
	}
	if !strings.Contains(out.Types, "type MainThingsNode struct") || strings.Count(out.Types, "type MainThingsNode struct") != 1 {
		t.Errorf("the recursive $ref must be emitted once:\n%s", out.Types)
	}
}

// squash makes runs of spaces one, so a check doesn't depend on gofmt's alignment.
func squash(s string) string { return strings.Join(strings.Fields(s), " ") }

func TestGoGenerationIsDeterministic(t *testing.T) {
	a, b := goOutput(t), goOutput(t)
	if a.Types != b.Types {
		t.Error("two runs differ")
	}
}
