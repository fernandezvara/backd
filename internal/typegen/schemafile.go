package typegen

import (
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/fernandezvara/backd/internal/registry"
)

// SchemaTypesFile is the name of the types file of a versioned collection, written next to its
// schema.vN.json files (design/schema-versioning.md §11.1). The migrations import from it.
const SchemaTypesFile = "schema.d.ts"

const schemaTypesPreamble = `/** An RFC 3339 timestamp in UTC, as the API sends and reads it. */
export type DateTimeString = string;

/** What a migration may read of a document besides its fields. It is read-only. */
export interface Meta {
  readonly id: string;
  readonly created_at: DateTimeString;
  readonly updated_at: DateTimeString;
  readonly created_by?: string;
  readonly updated_by?: string;
  readonly owner?: string | null;
  readonly org?: string;
  readonly team?: string;
  /** The write version (_meta.version), not the schema version. */
  readonly version: number;
}
`

// SchemaTypes returns the contents of schema.d.ts for a versioned collection: V1…VN, the fields
// of each kept version (read from its JSON file), Meta, and Current, the highest version. ok is
// false for a collection without schema.vN.json files. Warnings are what the generator could not
// express, with where.
func SchemaTypes(c *registry.Collection) (content string, warnings []string, ok bool, err error) {
	if !c.Versioned {
		return "", nil, false, nil
	}
	g := &gen{entries: map[string]string{}, aliases: map[string]string{}}
	var body strings.Builder
	for _, n := range c.SchemaVersions {
		raw, err := c.VersionSchema(n)
		if err != nil {
			return "", nil, true, err
		}
		prefix := fmt.Sprintf("V%d", n)
		conv := newConverter(raw, prefix, fmt.Sprintf("%s/%s %s ", c.Database, c.Name, registry.SchemaVersionFile(n)), g.warn)
		t := conv.typeOf(raw, "")
		for _, name := range slices.Sorted(keys(conv.defs)) {
			fmt.Fprintf(&body, "export type %s = %s;\n", name, conv.defs[name])
		}
		fmt.Fprintf(&body, "/** Fields of %s/%s in version %d (%s). */\nexport type %s = %s;\n\n", c.Database, c.Name, n, registry.SchemaVersionFile(n), prefix, t)
	}
	header := fmt.Sprintf("// Generated by `backd types` (generator %s) from %s. Do not edit: change the schema files and generate again.\n// The types of %s/%s for its migrations (schema.vN.ts import from here).\n\n",
		Version, schemaFileList(c), c.Database, c.Name)
	current := fmt.Sprintf("/** The current version of %s/%s. */\nexport type Current = V%d;\n", c.Database, c.Name, c.SchemaVersion)
	slices.Sort(g.warnings)
	return header + schemaTypesPreamble + "\n" + body.String() + current, g.warnings, true, nil
}

func schemaFileList(c *registry.Collection) string {
	names := make([]string, len(c.SchemaVersions))
	for i, n := range c.SchemaVersions {
		names[i] = registry.SchemaVersionFile(n)
	}
	return strings.Join(names, ", ")
}

// SchemaTypesPath is where a collection's schema.d.ts lives.
func SchemaTypesPath(c *registry.Collection) string { return filepath.Join(c.Dir, SchemaTypesFile) }

// SchemaFileState is how a collection's schema.d.ts stands against what the generator makes.
type SchemaFileState struct {
	Collection *registry.Collection
	Path       string
	Want       string
	Warnings   []string
	// Missing and Stale say the file is not there, or differs.
	Missing, Stale bool
}

// CheckSchemaFiles compares the schema.d.ts of every versioned collection of the realm (or of
// database db, when set) with what the generator makes. Collections without versions have none.
func CheckSchemaFiles(reg *registry.Registry, realm, db string) ([]SchemaFileState, error) {
	rl, ok := reg.Realms[realm]
	if !ok {
		return nil, fmt.Errorf("unknown realm %q", realm)
	}
	var out []SchemaFileState
	for _, dbName := range slices.Sorted(keys(rl.Databases)) {
		if db != "" && dbName != db {
			continue
		}
		for _, c := range rl.Databases[dbName].SortedCollections() {
			want, warnings, ok, err := SchemaTypes(c)
			if err != nil {
				return nil, err
			}
			if !ok {
				continue
			}
			st := SchemaFileState{Collection: c, Path: SchemaTypesPath(c), Want: want, Warnings: warnings}
			have, err := os.ReadFile(st.Path)
			switch {
			case os.IsNotExist(err):
				st.Missing = true
			case err != nil:
				return nil, err
			case string(have) != want:
				st.Stale = true
			}
			out = append(out, st)
		}
	}
	return out, nil
}

// WriteSchemaFiles writes the schema.d.ts of every versioned collection of the realm that is
// missing or stale, and returns the paths it wrote.
func WriteSchemaFiles(reg *registry.Registry, realm, db string) (written []string, warnings []string, err error) {
	states, err := CheckSchemaFiles(reg, realm, db)
	if err != nil {
		return nil, nil, err
	}
	for _, st := range states {
		warnings = append(warnings, st.Warnings...)
		if !st.Missing && !st.Stale {
			continue
		}
		if err := os.WriteFile(st.Path, []byte(st.Want), 0o644); err != nil {
			return written, warnings, err
		}
		written = append(written, st.Path)
	}
	return written, warnings, nil
}
