// Admin generates the document of the realm's admin API: its administration routes, the data
// routes past the collections' rules (typed per collection), and every function the
// administrators may run by hand, internal ones included, with their input and output schemas.
func Admin(reg *registry.Registry, realm string) (*Document, error) {
	rl, ok := reg.Realms[realm]
	if !ok {
		return nil, fmt.Errorf("unknown realm %q", realm)
	}
	if !rl.Settings.AuthEnabled {
		return nil, fmt.Errorf("realm %q has authentication disabled: it has no admin API", realm)
	}
	var base map[string]any
	if err := yaml.Unmarshal(api.OpenAPI, &base); err != nil {
		return nil, fmt.Errorf("the embedded contract: %w", err)
	}
	b := &builder{base: base, rl: rl, realm: realm, paths: map[string]any{}, extra: map[string]any{}, tags: map[string]bool{}}
	return b.admin()
}

// adminRoute reports whether the admin route (the path after `_admin/`) exists in this realm.
func (b *builder) adminRoute(route string) bool {
	s := b.rl.Settings
	if strings.HasPrefix(route, "users/{id}/export") {
		return s.Compliance.Export
	}
	first, _, _ := strings.Cut(route, "/")
	switch first {
	case "push":
		return s.Push != nil
	case "storage", "files":
		return s.Storage != nil || s.PublicStorage != nil
	case "consents":
		return len(s.Consents) > 0
	case "compliance":
		return true
	case "app-config":
		return b.rl.AppConfig != nil
	}
	return true
}

func (b *builder) admin() (*Document, error) {
	b.responses = map[string]any{}
	b.ids = map[string]bool{}
	b.addFileDetails()

	prefix := "/v1/{realm}/_admin/"
	paths, _ := b.base["paths"].(map[string]any)
	for _, p := range slices.Sorted(maps.Keys(paths)) {
		rest, ok := strings.CutPrefix(p, prefix)
		if !ok {
			continue
		}
		switch {
		case strings.HasPrefix(rest, "data/"), strings.HasPrefix(rest, "functions/"), strings.Contains(rest, "{database}"):
			continue // made per collection and per function below
		case strings.HasPrefix(rest, "openapi"):
			continue
		case !b.adminRoute(rest):
			continue
		}
		b.addStatic(p, "_admin/"+rest, nil)
	}

	for _, dbName := range slices.Sorted(maps.Keys(b.rl.Databases)) {
		db := b.rl.Databases[dbName]
		if len(db.Collections) > 0 {
			b.addStatic(prefix+"data/{database}/_batch", "_admin/data/"+dbName+"/_batch", map[string]string{"{database}": dbName})
		}
		for _, c := range db.SortedCollections() {
			b.collectionAt(dbName, c, true)
			b.addStatic(prefix+"data-checks/{database}/{collection}", "_admin/data-checks/"+dbName+"/"+c.Name,
				map[string]string{"{database}": dbName, "{collection}": c.Name})
		}
		if db.Functions == nil {
			continue
		}
		for _, name := range slices.Sorted(maps.Keys(db.Functions.Functions)) {
			fn := db.Functions.Functions[name]
			if fn.Mode != registry.ModeWebhook {
				b.adminInvoke(dbName, fn)
			}
			if fn.Schedule != nil {
				for _, verb := range []string{"pause", "resume"} {
					b.addStatic(prefix+"functions/{database}/{name}/"+verb, "_admin/functions/"+dbName+"/"+name+"/"+verb,
						map[string]string{"{database}": dbName, "{name}": name})
				}
			}
		}
	}

	doc := map[string]any{
		"openapi": "3.1.0",
		"info": map[string]any{
			"title":       b.realm + " admin API",
			"version":     "1",
			"summary":     "The admin API of the " + b.realm + " realm.",
			"description": "Generated by `backd openapi --admin` from the realm's configuration: users, API keys, secrets, audit, jobs, configuration and the data routes past the collections' rules (typed per collection), and every function an administrator may run by hand, internal ones included, with their input and output. For internal tooling: don't hand it to client applications.",
			"license":     baseLicense(b.base),
		},
		"servers":    b.base["servers"],
		"tags":       b.usedTags(),
		"security":   []any{map[string]any{"apiKey": []any{}}, map[string]any{"session": []any{}}},
		"paths":      b.paths,
		"components": b.prune(),
	}
	out, err := marshal(doc)
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(out)
	return &Document{JSON: out, Fingerprint: hex.EncodeToString(sum[:])}, nil
}

// adminInvoke adds the route that runs one function by hand, typed with its schemas.
func (b *builder) adminInvoke(db string, fn *registry.Function) {
	item := b.staticPath("/v1/{realm}/_admin/functions/{database}/{name}/invoke")
	if item == nil {
		return
	}
	cp := docutil.DeepCopy(item).(map[string]any)
	dropParams(cp, "realm", "database")
	// The contract's generic `name` parameter is the path's literal here.
	delete(cp, "parameters")
	alias := strutil.Pascal(db) + strutil.Pascal(fn.Name)
	tag := "functions"
	for _, op := range operations(cp) {
		dropParams(op, "realm", "database")
		op["tags"] = []any{tag}
		op["operationId"] = b.claim("adminInvoke" + alias)
		summary := "Run " + db + "/" + fn.Name + " by hand"
		if fn.Internal {
			summary += " (internal: no other route reaches it)"
		}
		op["summary"] = summary
		if in := b.functionSchema(fn, registry.InputSchemaFile, alias+"Input"); in != "" {
			if rb, ok := op["requestBody"].(map[string]any); ok {
				if content, ok := rb["content"].(map[string]any); ok {
					if aj, ok := content["application/json"].(map[string]any); ok {
						if sch, ok := aj["schema"].(map[string]any); ok {
							if props, ok := sch["properties"].(map[string]any); ok {
								props["input"] = map[string]any{"$ref": in}
							}
						}
					}
				}
			}
		}
		if out := b.functionSchema(fn, registry.OutputSchemaFile, alias+"Output"); out != "" && fn.Mode == registry.ModeSync {
			if responses, ok := op["responses"].(map[string]any); ok {
				if ok200, ok := responses["200"].(map[string]any); ok {
					ok200["content"] = map[string]any{"application/json": map[string]any{"schema": map[string]any{"$ref": out}}}
				}
			}
		}
	}
	b.tags[tag] = true
	b.paths["/v1/"+b.realm+"/_admin/functions/"+db+"/"+fn.Name+"/invoke"] = cp
}
