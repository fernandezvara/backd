// Package openapigen derives an OpenAPI 3.1 document for one realm from the generic contract
// (api/openapi.yaml) and the realm's loaded config: its collections with their schemas and
// features, its enabled authentication methods, its functions, and what its clients can reach.
package openapigen

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/fernandezvara/backd/api"
	"github.com/fernandezvara/backd/internal/registry"
	"github.com/fernandezvara/backd/internal/rules"
)

// Version is the generator's version: it changes when the output format does.
const Version = "1"

// Document is a generated OpenAPI document.
type Document struct {
	JSON        []byte
	Fingerprint string // of the document: what --check and caches compare
}

// Public generates the document of the realm's client API: collections a client can reach,
// the enabled authentication methods, non-internal functions and the realm's configuration.
// Internal functions, the admin API, rules and system collections are left out.
func Public(reg *registry.Registry, realm string) (*Document, error) {
	rl, ok := reg.Realms[realm]
	if !ok {
		return nil, fmt.Errorf("unknown realm %q", realm)
	}
	var base map[string]any
	if err := yaml.Unmarshal(api.OpenAPI, &base); err != nil {
		return nil, fmt.Errorf("the embedded contract: %w", err)
	}
	b := &builder{base: base, rl: rl, realm: realm, paths: map[string]any{}, extra: map[string]any{}, tags: map[string]bool{}}
	return b.public()
}

type builder struct {
	base  map[string]any
	rl    *registry.Realm
	realm string
	paths map[string]any
	// extra holds the schemas and responses this document adds to the contract's components.
	extra map[string]any
	// responses added by collections.
	responses map[string]any
	tags      map[string]bool
	ids       map[string]bool
}

func (b *builder) components(kind string) map[string]any {
	c, _ := b.base["components"].(map[string]any)
	m, _ := c[kind].(map[string]any)
	return m
}

func (b *builder) staticPath(p string) map[string]any {
	paths, _ := b.base["paths"].(map[string]any)
	m, _ := paths[p].(map[string]any)
	return m
}

// public assembles the document.
func (b *builder) public() (*Document, error) {
	b.responses = map[string]any{}
	b.ids = map[string]bool{}
	b.addFileDetails()

	prefix := "/v1/{realm}"
	auth := b.rl.Settings.AuthEnabled
	paths, _ := b.base["paths"].(map[string]any)
	for _, p := range slices.Sorted(keysOf(paths)) {
		rest, ok := strings.CutPrefix(p, prefix+"/")
		if !ok {
			continue
		}
		switch {
		case strings.HasPrefix(rest, "_auth/"):
			if auth && b.authEnabled(strings.TrimPrefix(rest, "_auth/")) {
				b.addStatic(p, rest, nil)
			}
		case rest == "_config":
			if b.rl.AppConfig != nil {
				b.addStatic(p, rest, nil)
			}
		case strings.HasPrefix(rest, "_consents"):
			if auth && len(b.rl.Settings.Consents) > 0 {
				b.addStatic(p, rest, nil)
			}
		}
	}
	if b.rl.AppConfig != nil {
		b.configSchema()
	}

	for _, dbName := range slices.Sorted(keysOf(b.rl.Databases)) {
		db := b.rl.Databases[dbName]
		reachable := false
		for _, c := range db.SortedCollections() {
			if b.reachable(c) {
				reachable = true
				b.collection(dbName, c)
			}
		}
		if reachable {
			b.addStatic(prefix+"/{database}/_batch", dbName+"/_batch", map[string]string{"{database}": dbName})
		}
		async := false
		if db.Functions != nil {
			for _, name := range slices.Sorted(keysOf(db.Functions.Functions)) {
				fn := db.Functions.Functions[name]
				if fn.Internal {
					continue
				}
				if fn.Mode == registry.ModeAsync {
					async = true
				}
				b.function(dbName, fn)
			}
		}
		if async || (db.Functions != nil && b.anyAsyncCallable(db)) {
			b.addStatic(prefix+"/{database}/_jobs/{id}", dbName+"/_jobs/{id}", map[string]string{"{database}": dbName})
		}
	}

	doc := map[string]any{
		"openapi": "3.1.0",
		"info": map[string]any{
			"title":       b.realm + " API",
			"version":     "1",
			"summary":     "The client API of the " + b.realm + " realm.",
			"description": "Generated by `backd openapi` from the realm's configuration: the collections clients can reach with their schemas, the enabled sign-in methods, and the realm's functions. Errors use backd's Error envelope.",
			"license":     baseLicense(b.base),
		},
		"servers":    b.base["servers"],
		"tags":       b.usedTags(),
		"security":   b.base["security"],
		"paths":      b.paths,
		"components": b.prune(),
	}
	out, err := marshal(doc)
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(out)
	return &Document{JSON: out, Fingerprint: hex.EncodeToString(sum[:])}, nil
}

func marshal(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func keysOf[V any](m map[string]V) func(func(string) bool) {
	return func(yield func(string) bool) {
		for k := range m {
			if !yield(k) {
				return
			}
		}
	}
}

// authEnabled reports whether the _auth route (the path after `_auth/`) exists in this realm.
func (b *builder) authEnabled(route string) bool {
	s := b.rl.Settings
	if strings.HasPrefix(route, "me/export") {
		return s.Compliance.Export
	}
	first, _, _ := strings.Cut(route, "/")
	switch first {
	case "signup":
		return s.Signup == registry.SignupOpen
	case "accept-invitation":
		return s.Signup != registry.SignupClosed || true
	case "verify-email", "reset-password", "email", "confirm-email-change", "revert-email-change":
		return s.Email != nil
	case "magic-link":
		return s.MagicLink.Enabled && s.Email != nil
	case "oauth", "identities":
		return len(s.Providers) > 0
	case "mfa":
		return !s.MFA.Off
	case "devices":
		return s.Push != nil
	case "consents":
		return len(s.Consents) > 0
	}
	return true // login, logout, me, password, sessions, token, reauth…
}

func (b *builder) anyAsyncCallable(db *registry.Database) bool {
	for _, fn := range db.Functions.Functions {
		if !fn.Internal && fn.Mode == registry.ModeAsync {
			return true
		}
	}
	return false
}

// reachable reports whether a client could use the collection: auth is disabled, or at least
// one of its rules isn't literally false (a missing rule allows nobody).
func (b *builder) reachable(c *registry.Collection) bool {
	if !b.rl.Settings.AuthEnabled {
		return true
	}
	for _, op := range []rules.Op{rules.Read, rules.Create, rules.Update, rules.Delete} {
		if r := c.Rules.For(op); r != nil && !r.AlwaysFalse() {
			return true
		}
	}
	return false
}

// allowed reports whether a client could use op on the collection.
func (b *builder) allowed(c *registry.Collection, op rules.Op) bool {
	if !b.rl.Settings.AuthEnabled {
		return true
	}
	r := c.Rules.For(op)
	return r != nil && !r.AlwaysFalse()
}

// addStatic copies the contract's path item under the realm, with the placeholders replaced.
func (b *builder) addStatic(contractPath, rel string, subst map[string]string) {
	item := b.staticPath(contractPath)
	if item == nil {
		return
	}
	cp := deepCopy(item).(map[string]any)
	drop := []string{"realm", "database", "collection", "function"}
	for k := range subst {
		drop = append(drop, strings.Trim(k, "{}"))
	}
	dropParams(cp, drop...)
	for _, m := range operations(cp) {
		dropParams(m, drop...)
	}
	path := "/v1/" + b.realm + "/" + rel
	for k, v := range subst {
		path = strings.ReplaceAll(path, k, v)
	}
	b.uniqueIDs(cp, "")
	for _, op := range operations(cp) {
		for _, t := range tagsOf(op) {
			b.tags[t] = true
		}
	}
	b.paths[path] = cp
}

var methods = []string{"get", "put", "post", "delete", "patch", "head", "options"}

func operations(item map[string]any) map[string]map[string]any {
	out := map[string]map[string]any{}
	for _, m := range methods {
		if op, ok := item[m].(map[string]any); ok {
			out[m] = op
		}
	}
	return out
}

func tagsOf(op map[string]any) []string {
	var out []string
	if ts, ok := op["tags"].([]any); ok {
		for _, t := range ts {
			if s, ok := t.(string); ok {
				out = append(out, s)
			}
		}
	}
	return out
}

// dropParams removes references to the contract's path parameters named in names.
func dropParams(node map[string]any, names ...string) {
	ps, ok := node["parameters"].([]any)
	if !ok {
		return
	}
	var kept []any
	for _, p := range ps {
		if m, ok := p.(map[string]any); ok {
			// A path parameter declared inline.
			if in, _ := m["in"].(string); in == "path" {
				if n, _ := m["name"].(string); slices.Contains(names, n) {
					continue
				}
			}
			if ref, ok := m["$ref"].(string); ok {
				drop := false
				for _, n := range names {
					if ref == "#/components/parameters/"+n {
						drop = true
					}
				}
				if drop {
					continue
				}
			}
		}
		kept = append(kept, p)
	}
	if len(kept) == 0 {
		delete(node, "parameters")
		return
	}
	node["parameters"] = kept
}

// claim returns id, or id with a number appended when it is taken, and marks it used.
func (b *builder) claim(id string) string {
	out := id
	for n := 2; b.ids[out]; n++ {
		out = fmt.Sprintf("%s%d", id, n)
	}
	b.ids[out] = true
	return out
}

// uniqueIDs makes the operation ids of a path item unique across the document.
func (b *builder) uniqueIDs(item map[string]any, suffix string) {
	for _, op := range operations(item) {
		if id, _ := op["operationId"].(string); id != "" {
			op["operationId"] = b.claim(id + suffix)
		}
	}
}

func (b *builder) usedTags() []any {
	declared := map[string]any{}
	if ts, ok := b.base["tags"].([]any); ok {
		for _, t := range ts {
			if m, ok := t.(map[string]any); ok {
				if n, ok := m["name"].(string); ok {
					declared[n] = m
				}
			}
		}
	}
	var out []any
	for _, t := range slices.Sorted(keysOf(b.tags)) {
		if d, ok := declared[t]; ok {
			out = append(out, d)
		} else if coll, ok := strings.CutPrefix(t, "data "); ok {
			out = append(out, map[string]any{"name": t, "description": "The data routes of the " + coll + " collection: past its rules, for administrators."})
		} else if db, rest, ok := strings.Cut(t, "/"); ok {
			out = append(out, map[string]any{"name": t, "description": "Documents of the " + rest + " collection of the " + db + " database."})
		} else if db, ok := strings.CutSuffix(t, " functions"); ok {
			out = append(out, map[string]any{"name": t, "description": "Server-side functions of the " + db + " database."})
		} else {
			out = append(out, map[string]any{"name": t, "description": t})
		}
	}
	return out
}

func deepCopy(v any) any {
	switch t := v.(type) {
	case map[string]any:
		out := make(map[string]any, len(t))
		for k, e := range t {
			out[k] = deepCopy(e)
		}
		return out
	case []any:
		out := make([]any, len(t))
		for i, e := range t {
			out[i] = deepCopy(e)
		}
		return out
	}
	return v
}

// rewriteRefs replaces $ref targets by the mapping (full pointer → pointer), in place.
func rewriteRefs(v any, mapping map[string]string) {
	switch t := v.(type) {
	case map[string]any:
		if ref, ok := t["$ref"].(string); ok {
			if to, ok := mapping[ref]; ok {
				t["$ref"] = to
			}
		}
		for _, e := range t {
			rewriteRefs(e, mapping)
		}
	case []any:
		for _, e := range t {
			rewriteRefs(e, mapping)
		}
	}
}

// prune returns the components reachable from the paths.
func (b *builder) prune() map[string]any {
	all := map[string]map[string]any{}
	for _, kind := range []string{"schemas", "responses", "parameters", "headers", "requestBodies", "examples"} {
		all[kind] = map[string]any{}
		for k, v := range b.components(kind) {
			all[kind][k] = v
		}
	}
	for k, v := range b.extra {
		all["schemas"][k] = v
	}
	for k, v := range b.responses {
		all["responses"][k] = v
	}
	keep := map[string]map[string]bool{}
	var visit func(v any)
	visit = func(v any) {
		switch t := v.(type) {
		case map[string]any:
			if ref, ok := t["$ref"].(string); ok {
				if rest, ok := strings.CutPrefix(ref, "#/components/"); ok {
					kind, name, _ := strings.Cut(rest, "/")
					if keep[kind] == nil {
						keep[kind] = map[string]bool{}
					}
					if !keep[kind][name] {
						keep[kind][name] = true
						if target, ok := all[kind][name]; ok {
							visit(target)
						}
					}
				}
			}
			for _, e := range t {
				visit(e)
			}
		case []any:
			for _, e := range t {
				visit(e)
			}
		}
	}
	visit(b.paths)
	out := map[string]any{}
	for kind, names := range keep {
		m := map[string]any{}
		for n := range names {
			if v, ok := all[kind][n]; ok {
				m[n] = v
			}
		}
		if len(m) > 0 {
			out[kind] = m
		}
	}
	if ss, ok := b.components("securitySchemes"), true; ok && len(ss) > 0 {
		out["securitySchemes"] = ss
	}
	return out
}

func baseLicense(base map[string]any) any {
	if info, ok := base["info"].(map[string]any); ok {
		return info["license"]
	}
	return nil
}
