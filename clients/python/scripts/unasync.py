"""Writes ``src/backd/_sync`` from ``src/backd/_async``.

The async client is the source. The sync one is the same code with ``async``/``await`` removed and
the names swapped, so the two cannot drift: CI runs ``python scripts/unasync.py --check``.

Files listed in ``HAND_WRITTEN`` have no generated twin (a thread and a task differ in more than
syntax); they live in ``_sync`` by hand.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "src" / "backd"
HAND_WRITTEN = {"realtime.py", "__init__.py"}
HEADER = "# Generated by scripts/unasync.py from _async/{name}. Do not edit: change the async file and run it again.\n"

# Order matters: the longer patterns first.
SUBSTITUTIONS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"\basync def\b"), "def"),
    (re.compile(r"\basync with\b"), "with"),
    (re.compile(r"\basync for\b"), "for"),
    (re.compile(r"\bawait "), ""),
    (re.compile(r"\bAwaitable\[([^\[\]]*(?:\[[^\[\]]*\])?[^\[\]]*)\]"), r"\1"),
    (re.compile(r"\bAwaitable, "), ""),
    (re.compile(r"\bAsyncIterator\b"), "Iterator"),
    (re.compile(r"\bAsyncIterable\b"), "Iterable"),
    (re.compile(r"\bAsyncGenerator\b"), "Generator"),
    (re.compile(r"\b__aenter__\b"), "__enter__"),
    (re.compile(r"\b__aexit__\b"), "__exit__"),
    (re.compile(r"\b__aiter__\b"), "__iter__"),
    (re.compile(r"\b__anext__\b"), "__next__"),
    (re.compile(r"\baclose\b"), "close"),
    (re.compile(r"\baread\b"), "read"),
    (re.compile(r"\baiter_bytes\b"), "iter_bytes"),
    (re.compile(r"\baiter_lines\b"), "iter_lines"),
    (re.compile(r"\bAsyncBaseTransport\b"), "BaseTransport"),
    (re.compile(r"\b_aio\b"), "_sio"),
    (re.compile(r"\b_async\b"), "_sync"),
    (re.compile(r"\bAsync(?=[A-Z])"), ""),
    (re.compile(r"\basync\b"), "sync"),
]


def convert(text: str) -> str:
    for pattern, repl in SUBSTITUTIONS:
        text = pattern.sub(repl, text)
    return text


def targets() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for src in sorted((ROOT / "_async").glob("*.py")):
        if src.name in HAND_WRITTEN:
            continue
        out[ROOT / "_sync" / src.name] = HEADER.format(name=src.name) + convert(src.read_text())
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale: list[str] = []
    for path, text in targets().items():
        if path.exists() and path.read_text() == text:
            continue
        stale.append(str(path.relative_to(ROOT.parent.parent)))
        if not check:
            path.parent.mkdir(exist_ok=True)
            path.write_text(text)
    if check and stale:
        print("out of date (run python scripts/unasync.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
